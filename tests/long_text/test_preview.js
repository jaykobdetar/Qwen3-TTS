const assert=require('node:assert/strict'),fs=require('node:fs');
const previewPath=__dirname+'/../../qwen_tts/cli/long_text/longtext_preview.js';
const source=fs.readFileSync(previewPath,'utf8').split('// UI:')[0];
const {reconcilePlayback,sectionAtTime,restoredAnchor}=new Function(source+'; return {reconcilePlayback,sectionAtTime,restoredAnchor};')();
const a={id:'a',url:'a-v1',start:0,end:2,duration:2},b={id:'b',url:'b-v1',start:2,end:5,duration:3};
assert.equal(reconcilePlayback([a],[a,b],'a','a-v1',1,false).action,'keep');
assert.equal(reconcilePlayback([a],[a,b],'a','a-v1',2,true).action,'advance');
assert.equal(reconcilePlayback([a],[a],'a','a-v1',2,true).action,'keep');
assert.equal(reconcilePlayback([a],[{...a,start:null,url:null}],'a','a-v1',1,false).action,'invalidate');
const replaced=reconcilePlayback([a],[{...a,url:'a-v2',end:1,duration:1}],'a','a-v1',1.5,false);
assert.equal(replaced.action,'replace');assert.equal(replaced.offset,.99);
const shifted={...b,start:4,end:7};
assert.equal(reconcilePlayback([a,b],[{...a,end:4,duration:4},shifted],'b','b-v1',1,false).action,'keep');
assert.equal(sectionAtTime([a,b],2).id,'b');assert.equal(sectionAtTime([a,b],5).id,'b');
assert.equal(sectionAtTime([{...a,start:null,end:null}],0),undefined);
assert.deepEqual(restoredAnchor([a,b],{id:'b',offset:1}),{id:'b',offset:1});
assert.equal(restoredAnchor([{...b,start:null}],{id:'b',offset:1}),null);
assert.deepEqual(restoredAnchor([{...b,duration:.5}],{id:'b',offset:2}),{id:'b',offset:.49});
console.log('12 playback reconciliation checks passed (append/no reload, waiting/resume, failed gaps, version replacement, shifted timing, boundaries).');
